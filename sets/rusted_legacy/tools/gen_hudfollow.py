#!/usr/bin/env python3
"""gen_hudfollow.py: make his wrist watch stay on the wrist and his gun ammo display stay on the gun.

His watch (modeldefs/holohud.txt) and gun display (modeldefs/holohud2.txt) are their own layers, drawn at ONE
pose per gun: the watch at the gun hand's Ready frame, the panel beside the gun at rest. The gun and the hand
animate (recoil, pump, the hell shotgun's spin), so in those frames the watch hangs in the air up to 19 cm off
the wrist and the panel up to 42 cm off the gun (tools/rl_watch_drift.py, tools/rl_hud_view.py). The method's
rule is that everything on the gun moves with it; this makes both follow.

  watch: w_dial*.md3 and every watch mesh have a frame per hand.md3 frame (153 frames; frame k is made for hand
         frame k). A pose whose hand frame is k shows the watch at frame k. Hand frames past 152 (the hell
         shotgun's 171-176) take the watch frame whose wrist is nearest (measured, residual reported).
  panel: the gun body's rigid motion from its Ready frame to the frame drawn (Kabsch on the body vertices,
         moving parts left out) is baked into new frames of copies of his panel meshes,
         models/common/rsrl_<gun>_<placement>_<mesh>.md3, one frame per pose.
A pose is every weapon sprite frame (every alt sprite of every block) whose watch or panel would be more than
1.0 cm off. Each pose v gets its own sprite names for the HUD layers (Y<v><base>, 27 bases), MODELDEF blocks
copied from his with those names and frames (modeldefs/rsrl_hudfollow.txt), and an entry in the table
(zscript/rsrl/rsrl_hudfollow.zs) that his DoomWeaponZ.Tick uses to swap the layers' sprites. Ready frames are
untouched: they draw exactly his blocks.

  RSQ_RL=sets/rusted_legacy/src python3 sets/rusted_legacy/tools/gen_hudfollow.py
"""
import json
import os
import re
import sys

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
SET = os.path.dirname(HERE)
SRC = os.path.join(SET, 'src')
os.environ.setdefault('RSQ_RL', SRC)
sys.path.insert(0, HERE)
import rl_measure as R  # noqa: E402
import md3label  # noqa: E402

FILES = {'pistol': 'pistol', 'shotgun': 'shotgun', 'ssg': 'ssg', 'chaingun': 'chaingun', 'plasma': 'plasmarifle',
         'rocket': 'rocketlauncher', 'hellshotgun': 'hellshotgun', 'incinerator': 'incinerator', 'bfg': 'bfg9000',
         'heatwave': 'heatwave', 'chainsaw': 'chainsaw', 'fist': 'fist'}
ACTOR = dict(R.ACTOR, fist='RLFist')
BASES = ['WH%02d' % i for i in range(12)] + ['HH0%d' % i for i in range(7)] + ['HH1%d' % i for i in range(7)] + ['HH20']
B36 = '0123456789ABCDEFGHIJKLMNOPQRSTUVWXYZ'
THRESH = 1.0
WATCH_LAYERS = list(range(1050, 1060))
PANEL_LAYERS = list(range(1060, 1067))


def code(b):
    s = BASES[b]
    return {'W': 'W', 'H': {'0': 'H', '1': 'I', '2': 'J'}}[s[0]] if s[0] == 'W' else {'0': 'H', '1': 'I', '2': 'J'}[s[2]]


def vname(v, b):
    s = BASES[b]
    tail = ('W' + B36[int(s[2:])]) if s.startswith('WH') else ({'0': 'H', '1': 'I', '2': 'J'}[s[2]] + s[3])
    return 'Y' + B36[v] + tail


def strip(t):
    return re.sub(r'//[^\n]*', '', t)


def blocks(path, actor):
    return re.findall(r'(Model\s+' + actor + r'\s*\{.*?\n\})', open(path, errors='replace').read(), re.S)


def frame_map(gun, gun_mesh):
    """(sprite, letter) -> (gun mesh frame or None, hand.md3 frame or None)"""
    t = strip(open(os.path.join(SRC, 'modeldefs/weapons/%s.txt' % FILES[gun]), errors='replace').read())
    out = {}
    for b in re.findall(r'Model\s+' + ACTOR[gun] + r'\s*\{(.*?)\n\}', t, re.S):
        path, slots = '', {}
        for line in b.splitlines():
            m = re.match(r'\s*Path\s+"([^"]+)"', line)
            if m:
                path = m.group(1)
            m = re.match(r'\s*Model\s+(\d+)\s+"([^"]+)"', line)
            if m:
                slots[int(m.group(1))] = (path + '/' + m.group(2)).lower()
            for s, l, slot, fr in re.findall(r'FrameIndex\s+(\w{4})\s+(\w)\s+(\d+)\s+(\d+)', line):
                g, h = out.get((s, l), (None, None))
                mp = slots.get(int(slot), '')
                if gun_mesh and mp == gun_mesh.lower():
                    g = int(fr)
                if mp.endswith('/hand.md3'):
                    h = int(fr)
                out[(s, l)] = (g, h)
    return out


def kabsch(P, Q):
    pc, qc = P.mean(0), Q.mean(0)
    U, S, Vt = np.linalg.svd((P - pc).T @ (Q - qc))
    d = np.sign(np.linalg.det(Vt.T @ U.T))
    Rm = Vt.T @ np.diag([1, 1, d]) @ U.T
    return Rm, qc - Rm @ pc


def flu(xyz, pl):
    return R.flu_pl(xyz, pl)


def placement_affine(pl):
    b = flu(np.zeros((1, 3)), pl)[0]
    A = np.stack([flu(np.eye(3)[i:i + 1], pl)[0] - b for i in range(3)], 1)
    return A, b


def block_pl(text):
    return R.block_pl(text)


def main():
    hand = R.md3('models/hand/hand.md3')
    H = [np.vstack([R.to_flu(md3label.surf_xyz(s)[f]) for s in hand['surfs']]) for f in range(hand['nframes'])]
    WN = 153
    mdl_out = ['// GENERATED by sets/rusted_legacy/tools/gen_hudfollow.py: his watch and gun display, one copy per',
               '// animated pose so they stay on the wrist and on the gun. Do not edit by hand.', '']
    zs_cases = []
    report = []
    maxv = 0
    meshdir = os.path.join(SRC, 'models', 'common')
    for f in os.listdir(meshdir):
        if f.startswith('rsrl_') and f.endswith('.md3'):
            os.remove(os.path.join(meshdir, f))
    for gun in ['pistol', 'shotgun', 'ssg', 'chaingun', 'plasma', 'rocket', 'hellshotgun', 'incinerator', 'bfg',
                'heatwave', 'chainsaw', 'fist']:
        actor = ACTOR[gun]
        card = None
        if gun != 'fist':
            card = json.load(open(os.path.join(SET, 'cards', gun, 'rl_%s.json' % gun)))
        gun_mesh = card['models']['0'] if card else None
        fmap = frame_map(gun, gun_mesh)
        # watch rest frame and wrist
        wb = blocks(os.path.join(SRC, 'modeldefs/holohud.txt'), actor)
        wmesh = re.search(r'Model\s+0\s+"([^"]+)"', wb[0]).group(1)
        wf = int(re.search(r'FrameIndex\s+\S+\s+\S\s+0\s+(\d+)', wb[0]).group(1))
        dial = R.md3('models/common/' + wmesh)
        D = np.vstack([R.flu_pl(md3label.surf_xyz(s)[wf], dict(scale=[-1, 1, 1], off=[0, -24, -10])) for s in dial['surfs']])
        dc = D.mean(0)
        wid = np.where(np.linalg.norm(H[wf] - dc, axis=1) < 6.0)[0]
        # gun body
        pb = []
        if card:
            gm = R.md3(gun_mesh)
            moving = {p['surf'] for p in card['parts'] if p['role'] not in ('body', 'deco')}
            f0r = card['ready_frames']['0']

            def body(f):
                return np.vstack([R.to_flu(md3label.surf_xyz(s)[f]) for i, s in enumerate(gm['surfs']) if i not in moving])
            Pbody = body(f0r)
            pb = blocks(os.path.join(SRC, 'modeldefs/holohud2.txt'), actor)
            pcs = [np.array(card['hud']['gun_display']['centre'])] if pb else []
        poses = {}		# (watch frame, gun frame) -> v
        table = {}		# (sprite, letter) -> v
        worst = (0, 0)
        for key, (g, h) in sorted(fmap.items()):
            wk, wdrift = None, 0.0
            if h is not None and h < len(H) and h != wf:
                Rm, t = kabsch(H[wf][wid], H[h][wid])
                wdrift = float(np.linalg.norm(Rm @ dc + t - dc))
                if h < WN:
                    wk = h
                else:
                    wk = min(range(WN), key=lambda k: float(np.linalg.norm(H[k][wid] - H[h][wid], axis=1).mean()))
            pdrift = 0.0
            gk = None
            if pb and g is not None and g != f0r and g < gm['nframes']:
                Rm, t = kabsch(Pbody, body(g))
                pdrift = float(np.linalg.norm(Rm @ pcs[0] + t - pcs[0]))
                gk = g
            if wdrift <= THRESH and pdrift <= THRESH:
                continue
            pk = (wk if wdrift > THRESH else None, gk if pdrift > THRESH else None)
            if pk not in poses:
                poses[pk] = len(poses) + 1
            table[key] = poses[pk]
            worst = max(worst, (wdrift, pdrift))
        if not poses:
            report.append('%-11s no pose moves the watch or the panel more than %.1f cm' % (gun, THRESH))
            continue
        if len(poses) > 35:
            sys.exit('%s: %d poses, more than the 35 sprite names allow' % (gun, len(poses)))
        maxv = max(maxv, len(poses))
        # panel meshes, baked per placement
        baked = {}
        if pb:
            gframes = sorted({pk[1] for pk in poses if pk[1] is not None})
            gidx = {g: i for i, g in enumerate(gframes)}
            for bi, btxt in enumerate(pb):
                pl = block_pl(btxt)
                A, b0 = placement_affine(pl)
                Ainv = np.linalg.inv(A)
                for mname in sorted(set(re.findall(r'Model\s+\d+\s+"([^"]+)"', btxt))):
                    tag = 'x%g_o%g_%g_%g' % (abs(pl['scale'][1]), *pl['off'])
                    out = 'rsrl_%s_%s_%s' % (gun, tag.replace('-', 'm').replace('.', 'p'), mname[:-4])
                    if out in baked.values() or not gframes:
                        baked[(bi, mname)] = out
                        continue
                    m = md3label.read_raw(os.path.join(meshdir, mname))
                    frames = []
                    for g in gframes:
                        Rm, t = kabsch(Pbody, body(g))
                        frames.append((Rm, t))
                    for s in m['surfs']:
                        raw = np.frombuffer(s['xyz'], dtype='<i2').reshape(s['nframes'], s['nverts'], 4)
                        x0 = raw[0, :, :3].astype(float) / 64.0
                        F = flu(x0, pl)
                        new = []
                        for Rm, t in frames:
                            Fm = (Rm @ F.T).T + t
                            xm = (Ainv @ (Fm - b0).T).T
                            v = raw[0].copy()
                            v[:, :3] = np.clip(np.round(xm * 64), -32768, 32767)
                            new.append(v)
                        s['xyz'] = np.stack(new).astype('<i2').tobytes()
                        s['nframes'] = len(frames)
                    fr0 = m['frames'][0]
                    m['frames'] = [bytearray(fr0) for _ in frames]
                    m['tags'] = []
                    m['ntags'] = 0
                    m['nframes'] = len(frames)
                    md3label.write_raw(m, os.path.join(meshdir, out + '.md3'), ['p%d' % g for g in gframes], [])
                    baked[(bi, mname)] = out
        # MODELDEF copies
        for pk, v in sorted(poses.items(), key=lambda x: x[1]):
            wk, gk = pk
            for btxt in wb:
                t = btxt
                t = re.sub(r'FrameIndex\s+(WH\d\d)\s+(\w)\s+(\d+)\s+(\d+)',
                           lambda m: 'FrameIndex %s %s %s %s' % (vname(v, BASES.index(m.group(1))), m.group(2), m.group(3),
                                                                 wk if wk is not None else m.group(4)), t)
                mdl_out.append('// %s pose %d: watch frame %s' % (actor, v, wk if wk is not None else '%d (his)' % wf))
                mdl_out.append(t)
            for bi, btxt in enumerate(pb):
                t = btxt
                if gk is not None:
                    gi = gframes.index(gk)
                    t = re.sub(r'(Model\s+\d+\s+)"([^"]+)"', lambda m: '%s"%s.md3"' % (m.group(1), baked[(bi, m.group(2))]), t)
                    t = re.sub(r'(FrameIndex\s+\w{4}\s+\w\s+\d+\s+)0\b', lambda m: m.group(1) + str(gi), t)
                t = re.sub(r'FrameIndex\s+(HH\d\d)\b', lambda m: 'FrameIndex ' + vname(v, BASES.index(m.group(1))), t)
                mdl_out.append('// %s pose %d: panel %s' % (actor, v, 'gun frame %d' % gk if gk is not None else 'his'))
                mdl_out.append(t)
        zs_cases.append((actor, table))
        report.append('%-11s %3d poses over %3d sprite frames; worst before: watch %.1f cm, panel %.1f cm'
                      % (gun, len(poses), len(table), worst[0], worst[1]))
    open(os.path.join(SRC, 'modeldefs/rsrl_hudfollow.txt'), 'w').write('\n'.join(mdl_out) + '\n')

    # ZScript table + sprite registration
    z = ['// GENERATED by sets/rusted_legacy/tools/gen_hudfollow.py. Do not edit by hand.', '//']
    z += ['// ' + r for r in report]
    z += ['', 'class RSRL_HudSprites : Actor', '{', '\tStates', '\t{', '\tSpawn:']
    for v in range(1, maxv + 1):
        z.append('\t\t' + ' '.join('%s A 0;' % vname(v, b) for b in range(len(BASES))))
    z += ['\t\tStop;', '\t}', '}', '', 'extend class RSRL_HudFollow', '{',
          '\tconst POSES = %d;' % maxv,
          '\tconst BASES = %d;' % len(BASES),
          '\tstatic name BaseName(int b)', '\t{', '\t\tswitch (b)', '\t\t{'] + \
        ['\t\tcase %d: return \'%s\';' % (i, n) for i, n in enumerate(BASES)] + \
        ['\t\t}', '\t\treturn \'TNT1\';', '\t}', '',
         '\t// pose v\'s copy of base sprite b: Y<v><W + watch layer | H/I/J + panel layer>',
         '\tstatic name VarName(int v, int b)', '\t{',
         '\t\tstring c = "0123456789ABCDEFGHIJKLMNOPQRSTUVWXYZ";', '\t\tstring t;', '\t\tswitch (b)', '\t\t{'] + \
        ['\t\tcase %d: t = "%s"; break;' % (i, vname(1, i)[2:]) for i in range(len(BASES))] + \
        ['\t\t}', '\t\treturn "Y" .. c.Mid(v, 1) .. t;', '\t}', '',
          '\t// the pose of the weapon frame drawn (0 = his Ready pose: his blocks as they are)',
          '\tstatic int Pose(Weapon w, SpriteID spr, int frame)', '\t{', '\t\tname c = w.GetClassName();']
    for actor, table in zs_cases:
        z.append('\t\tif (c == \'%s\')' % actor)
        z.append('\t\t{')
        z.append('\t\t\tswitch (frame)')
        z.append('\t\t\t{')
        letters = sorted({k[1] for k in table})
        for l in letters:
            z.append('\t\t\tcase %d:\t// %s' % (ord(l) - ord('A'), l))
            bypose = {}
            for (sp, ll), v in sorted(table.items()):
                if ll == l:
                    bypose.setdefault(v, []).append(sp)
            for v, sps in sorted(bypose.items()):
                z.append('\t\t\t\tif (%s) return %d;' % (' || '.join('spr == Actor.GetSpriteIndex(\'%s\')' % x for x in sps), v))
            z.append('\t\t\t\tbreak;')
        z.append('\t\t\t}')
        z.append('\t\t\treturn 0;')
        z.append('\t\t}')
    z += ['\t\treturn 0;', '\t}', '}', '']
    open(os.path.join(SRC, 'zscript/rsrl/rsrl_hudfollow_table.zs'), 'w').write('\n'.join(z))
    json.dump({a: {'%s%s' % k: v for k, v in tb.items()} for a, tb in zs_cases},
              open(os.path.join(SET, 'cards', 'hud_follow.json'), 'w'), indent=0, sort_keys=True)
    print('\n'.join(report))


if __name__ == '__main__':
    main()
