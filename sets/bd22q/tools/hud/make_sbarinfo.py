"""make_sbarinfo.py -- src/SBARINFO.rsq: BD22's own status bars (brutal22test6.pk3 SBARINFO.BD, every HUD style) with
their ammo numbers read from this pack's HUD items instead of the weapon's two ammo types (owner 2026-10-27 20:47:
"HUD Ammo: Magazine + Reserve / Reserve Only").

    python3 -B tools/hud/make_sbarinfo.py [/path/to/brutal22test6.pk3]

Why: BD22 draws `ammo2` as the magazine and `ammo1` as the reserve when the gun `UsesSecondaryAmmo`. That is right for
the guns whose magazine is their AmmoType2 (pistol, rifle, SMG, ...), wrong for this pack's real magazines (Unmaker,
Minigun, Flamethrower, Machinegun -- whose AmmoType2 is its 40 mm -- and the drum/box/cylinder guns: their magazine is
an RSQ_Mag_<gun> item, and the reserve item also holds the rounds lent to BD22's fire code), and it cannot be switched
off. zscript/rsq/counters.zs (RSQ_Counters.Hud) sets, every tic, for the gun in hand:
    RSQ_HudMag  the rounds in the magazine          RSQ_HudRes  the reserve (the pouch, never the loaded rounds)
    RSQ_HudHasMag  1 when a magazine is to be shown (the gun has one AND the option is Magazine + Reserve)
    RSQ_HudMagOff / RSQ_HudHasMagOff  the same for a dual gun in the off hand
Transform (every style, every line, nothing else changed):
    `ammo2` -> `RSQ_HudMag`;  `ammo1` -> `RSQ_HudRes` (an item's count: `ammo X` takes Ammo classes only);
    `UsesSecondaryAmmo` -> `InInventory RSQ_HudHasMag, 1`  (and its `not` form);
    `drawimage ammoicon2` not for the Machinegun (its AmmoType2 is the 40 mm: a rocket icon by its magazine count);
    the off hand's magazine is added on the classic bar (above the magazine) and the ZDoom-style fullscreen
    (left of the magazine) -- the two styles the rig shows (screenblocks 10 / 11, sbartype1, BD22's default).
"""
import os as _dpo, sys as _dps; _dps.path.append(_dpo.path.normpath(_dpo.path.join(_dpo.path.dirname(_dpo.path.abspath(__file__)), '../../../../tools'))); import depot as _DP	# Depot paths (tools/depot.py)
import os, re, sys, zipfile
HERE = os.path.dirname(os.path.abspath(__file__)); REPO = os.path.dirname(os.path.dirname(HERE))
PK3 = sys.argv[1] if len(sys.argv) > 1 else (_DP.GAMEDATA + '/brutal22test6.pk3')
src = zipfile.ZipFile(PK3).read('SBARINFO.BD').decode('latin-1')
n = {'ammo2': 0, 'ammo1': 0, 'usessec': 0, 'off': 0}
def line(l):
    l2, k = re.subn(r'(?i)(?<![\w])ammo2(?![\w])', 'RSQ_HudMag', l); n['ammo2'] += k
    l2, k = re.subn(r'(?i)(?<![\w])ammo1(?![\w])', 'RSQ_HudRes', l2); n['ammo1'] += k
    # the Machinegun's AmmoType2 is its 40 mm (AmmoRocket): BD22's ammoicon2 would put a rocket by its magazine count
    mi = re.match(r'(?i)^(\s*)(drawimage\s+ammoicon2\s*,.*;)\s*$', l2)
    if mi:
        n['icon2'] = n.get('icon2', 0) + 1
        l2 = '%sIsSelected not "Machinegun" { %s }\t// rsq: its AmmoType2 is the 40 mm, not its magazine' % (mi.group(1), mi.group(2))
    m = re.match(r'(?i)^(\s*)UsesSecondaryAmmo(\s+not)?\s*(//.*)?$', l2)
    if m:
        n['usessec'] += 1
        l2 = '%sInInventory%s RSQ_HudHasMag, 1%s' % (m.group(1), ' not' if m.group(2) else '', ('\t' + m.group(3)) if m.group(3) else '')
    return l2
out = [line(l) for l in src.splitlines()]
txt = '\n'.join(out)
# the off hand's magazine: classic bar (above the magazine), ZDoom-style fullscreen (left of the magazine)
a = '\t\t\tdrawnumber 3, HUDFONT_DOOM, untranslated, RSQ_HudMag, alignment(center), -25, 171;\n'
assert txt.count(a) == 1, 'classic bar magazine line'
txt = txt.replace(a, a + '\t\t\tInInventory RSQ_HudHasMagOff, 1 { drawnumber 3, HUDFONT_DOOM, untranslated, RSQ_HudMagOff, alignment(center), -25, 152; }\t// rsq: off hand\n'); n['off'] += 1
b = '\t\t\t\t\tdrawnumber 2147483647, HUDFONT_DOOM, untranslated, RSQ_HudMag, drawshadow, -55, -38;\n'
i = txt.index('InInventory sbartype1,1'); j = txt.index(b, i)
txt = txt[:j + len(b)] + '\t\t\t\t\tInInventory RSQ_HudHasMagOff, 1 { drawnumber 2147483647, HUDFONT_DOOM, untranslated, RSQ_HudMagOff, drawshadow, -110, -38; }\t// rsq: off hand\n' + txt[j + len(b):]; n['off'] += 1
head = ('// GENERATED by tools/hud/make_sbarinfo.py from brutal22test6.pk3 SBARINFO.BD -- do not edit by hand.\n'
        '// BD22\'s status bars; the ammo numbers come from zscript/rsq/counters.zs RSQ_Counters.Hud (HUD Ammo option).\n')
open(os.path.join(REPO, 'src', 'SBARINFO.rsq'), 'w', newline='\n').write(head + txt + '\n')
print('SBARINFO.rsq: %d lines; replaced ammo2 x%d, ammo1 x%d, UsesSecondaryAmmo x%d; ammoicon2 kept off the Machinegun x%d; off-hand magazine added in %d styles'
      % (len(out), n['ammo2'], n['ammo1'], n['usessec'], n.get('icon2', 0), n['off']))
