#!/usr/bin/env python3
"""handfit_donors.py -- Ermac gun-hand and support-hand rows for card donors that have none, by the kit's one method.

    RSQ_ERMAC=<folder with hand/hand.md3 + hand2.md3 (Ermac's full hands; the RSQ_RustedLegacy build has them)> \\
    python3 tools/ms/handfit_donors.py MS_BD_Shotgun MS_BD_Ssg ... [--write] [--regions work/gripregions.json]

The method is tools/kit/handfit_cards.py's, unchanged: take Ermac's already-posed hand frame for the gun's type, keep
the pose, and find the TRANSLATION that puts its measured gripping face (gripregions.json, from tools/hqt/gripmeasure.py)
onto the gun by ICP, searched in a tight window round the card's own grip point; the support hand's cylinder stand-in
the same way round the card's support feature. What differs from handfit_cards.py is only where the inputs come from:
the donor's block in `modeldef` (placement, rest frame) and its card (grip line, support feature), not the old c2q build.

--write APPENDS slots: to redo a fit, restore zscript_depot/rsq/handtable.zs first (git checkout <before> -- that file).
Output: one sheet per donor in work/handfit/<donor>.png (side + bottom: gun, gun hand, support hand, the card's points),
one line per donor, and with --write the rows appended to zscript_depot/rsq/handtable.zs as new slots plus
`if (donor == ...) return N;` lines in a GENERATED block. LOOK AT THE SHEETS before --write lands anywhere.
"""
import os, sys, re, json
import numpy as np

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
sys.path.insert(0, os.path.join(ROOT, 'tools', 'kit'))
sys.path.insert(0, os.path.join(ROOT, 'tools', 'handfit', 'core', 'hands_tool'))
sys.path.insert(0, os.path.join(ROOT, 'tools', 'handfit', 'blender'))
import gunview, hudrender, gunplace  # noqa: E402
import handfit_cards as HC  # noqa: E402
from handfit_addon import parse_card  # noqa: E402

TYPE = {  # donor -> handfit_cards.POSE key (which Ermac pose the gun type takes)
    'MS_BD_Shotgun': 'shotgun', 'MS_BD_Ssg': 'breakaction', 'MS_BD_Minigun': 'chaingun', 'MS_BW_1911': 'pistol', 'MS_HX_Nuker': 'bfg',
    'MS_BD_Revolver': 'revolver', 'MS_CW_Nailgun': 'smg', 'MS_PD_Cannon': 'launcher',   # Golden Souls 1 (M3, 2026-11-08)
    'MS_BD_Railgun': 'railgun',
}
# where the support hand goes when the card's `support feature` is the one-handed placeholder (owner, 2026-11-08):
#   ('under', surf N, frac): the underside of surface N (the barrels) at frac of the way along that surface;
#   ('part', role, pose): the centroid of the card part with that role (the minigun's owner-confirmed handlebar), with
#   the Ermac support pose named (91 = fist on a vertical grip).
SUPPORT_FROM = {
    'MS_BD_Ssg': ('under', 0, 0.5),          # owner: "ssg support hand needs to be under the barrel"
    'MS_BD_Railgun': ('under_at', 2, 'card'),  # owner 19:55 "support hand on rifle": under the body at the card's support x (forward of the magazine)
    'MS_BD_Minigun': ('part', 'support', 91),   # the side bar is the off-hand handlebar (card, owner 2026-10-31)
}
# fits looked at on their sheets (work/handfit/<donor>.png) and refused, with the reason; a refused donor is reported, never written
REJECT = {
    'MS_PD_Cannon': 'the pirate cannon is a metre-long carried barrel: the ICP put the hand inside its body. No hand until Handfit (Blender)',
    'MS_VP_Chainsaw': 'owner, 2026-11-08: the fit is "a sad embarrassing mess"; chainsaws go without hands until Handfit (Blender)',
    'MS_VP_Minigun': 'the card\'s grip line (centroid-based) sits on the ammo box, not on the pistol grip under the receiver; the hand landed on the box. Needs the owner\'s grip point (Handfit, or a corrected card)',
}
TABLE = os.path.join(ROOT, 'zscript_depot', 'rsq', 'handtable.zs')
BEGIN = '\t\t// ---- GENERATED by tools/ms/handfit_donors.py: Ermac hands fitted on the card (ICP on the grip line / support feature)'
END = '\t\t// ---- END GENERATED (handfit_donors)'


def block(donor):
    md = open(os.path.join(ROOT, 'modeldef'), encoding='utf-8', errors='replace').read()
    m = re.search(r'^Model %s\n\{(.*?)\n\}' % re.escape(donor), md, re.S | re.M)
    if not m: raise SystemExit('%s: no Model block in modeldef' % donor)
    b = m.group(1)
    g = lambda pat, d=None: (re.search(pat, b).group(1) if re.search(pat, b) else d)
    scale = [float(x) for x in g(r'Scale ([-\d. ]+)', '1 1 1').split()]
    off = [float(x) for x in g(r'\n\s*Offset ([-\d. ]+)', '0 0 0').split()]
    return dict(path=g(r'Path "([^"]+)"'), model=g(r'Model 0 "([^"]+)"'), scale=scale, off=[off[0], off[1]],
                zoff=float(g(r'ZOffset ([-\d.]+)', '0')), ao=(float(g(r'AngleOffset ([-\d.]+)', '0')), float(g(r'PitchOffset ([-\d.]+)', '0')), float(g(r'RollOffset ([-\d.]+)', '0'))),
                frame=int(g(r'FrameIndex \w+ A 0 (\d+)', '0')))


def item(b):
    return dict(path=os.path.join(ROOT, b['path'], b['model']), frame=b['frame'], scale=b['scale'], off=[b['off'][0], b['off'][1], b['zoff']], ao=b['ao'], color=[150, 155, 170])


def to_flu(V, it):
    return gunview.to_fl(gunplace.to_local_ao(np.asarray(V, float).reshape(-1, 3), it))


def gun_points(it):
    """surface points of the gun at its rest frame in the controller frame (cm): the triangles' vertices + centroids"""
    pts = []
    for tris, raw in gunview.item_mesh(it):
        P = to_flu(raw, it); pts.append(P); pts.append(P[tris].mean(1))
    return np.vstack(pts)


def fit(donor, regions, ermac, outdir):
    HC.REGIONS = regions; HC.ERMAC = os.path.join(ermac, 'hand')
    b = block(donor); it = item(b)
    card_path = [f for f in os.listdir(os.path.join(ROOT, b['path'])) if f.endswith('.card') and not f.endswith('.blend.card')]
    card = parse_card(os.path.join(ROOT, b['path'], card_path[0]))
    pts = card['points']
    raw = open(os.path.join(ROOT, b['path'], card_path[0]), encoding='utf-8', errors='replace').read()
    sup_line = next((l for l in raw.splitlines() if l.strip().startswith('support ')), '')
    if 'placeholder' in sup_line: pts.pop('support', None)   # "one-handed gun; placeholder": not a measured point, no support fit
    sup_pose = None
    if donor in SUPPORT_FROM:
        spec = SUPPORT_FROM[donor]
        if spec[0] == 'under':
            _, surf, frac = spec
            surfs = gunview.item_mesh(dict(it)); V = np.asarray(surfs[surf][1], float)   # the barrels, model space, rest frame
            x = V[:, 0].min() + frac * (V[:, 0].max() - V[:, 0].min())                 # frac of the way along the barrels
            band = V[np.abs(V[:, 0] - x) < 2.0]
            low = band[band[:, 2].argmin()]                                             # their underside there
            pts['support'] = [float(x), float(band[:, 1].mean()), float(low[2])]
        elif spec[0] == 'under_at':
            _, surf, xs = spec
            m = re.search(r'^\s+support\s+feature\s+\w+\s+\[([^\]]*)\]', raw, re.M)
            x = float(m.group(1).split(',')[0]) if xs == 'card' and m else float(xs)
            V = np.asarray(gunview.item_mesh(dict(it))[surf][1], float); band = V[np.abs(V[:, 0] - x) < 2.0]
            if len(band) == 0: band = V[np.argsort(np.abs(V[:, 0] - x))[:50]]
            low = band[band[:, 2].argmin()]
            pts['support'] = [float(x), float(band[:, 1].mean()), float(low[2])]
        elif spec[0] == 'part':
            _, role, sup_pose = spec
            m = re.search(r'^\s+%s\s+surf \d+\s+rest \[([^\]]*)\]' % role, raw, re.M)
            if m: pts['support'] = [float(v) for v in m.group(1).split(',')]
    if 'grip_top' not in pts: return None, '%s: card has no grip line' % donor
    if np.allclose(pts['grip_top'], pts['grip_bottom']): return None, '%s: the card\'s grip line is a single point (the grip guesser found nothing): needs a measured grip' % donor
    if donor in REJECT: return None, '%s: NOT written: %s' % (donor, REJECT[donor])
    palm = to_flu([(np.array(pts['grip_top']) + np.array(pts['grip_bottom'])) / 2], it)[0]
    sup_at = to_flu([pts['support']], it)[0] if 'support' in pts else None
    typ = TYPE.get(donor, 'rifle'); two, one, sup, kind, trig = HC.POSE[typ]
    if sup_pose is not None: sup = sup_pose
    gp = gun_points(it)
    t, err, why = HC.fit_gun(gp, palm, 'hand:%d' % two)
    if t is None: return None, '%s: gun hand: %s' % (donor, why)
    row = dict(donor=donor, one=HC.GUN_LETTER[one], two=HC.GUN_LETTER[two], sup=HC.SUP_LETTER[sup], trig='',
               hook=(round(t[1], 3), round(t[2], 3), round(-t[0], 3)), rot=(0, 0, 0), srot=(0, 0, 0))
    info = '%-16s %-11s gun hand:%d at F%+.1f L%+.1f U%+.1f (face %.2f cm from the gun)' % (donor, typ, two, t[0], t[1], t[2], err)
    if kind == 'same':
        t2 = t.copy(); sp = palm / 100.0; info += '; support cups the gun hand'
    elif sup_at is None:
        row.update(sup='', shook=(0, 0, 0), spoint=(0, 0, 0)); info += '; no support feature on the card: support off'
        sheet(donor, it, [HC.hand_item('hand', two, t)], [(*palm, 'grip', (255, 200, 60))], outdir); return row, info
    else:
        t2, err2, fp, why2 = HC.fit_support(gp, None, sup_at, 'hand2:%d' % sup)
        if t2 is None:
            row.update(sup='', shook=(0, 0, 0), spoint=(0, 0, 0)); info += '; support: ' + why2
            sheet(donor, it, [HC.hand_item('hand', two, t)], [(*palm, 'grip', (255, 200, 60)), (*sup_at, 'support', (120, 230, 140))], outdir); return row, info
        sp = np.array(fp) / 100.0; info += '; support hand2:%d at F%+.1f L%+.1f U%+.1f (%.2f cm)' % (sup, t2[0], t2[1], t2[2], err2)
    row.update(shook=(round(t2[1], 3), round(t2[2], 3), round(-t2[0], 3)), spoint=tuple(float(x) for x in np.round(sp, 3)))
    marks = [(*palm, 'grip', (255, 200, 60))] + ([(*sup_at, 'support', (120, 230, 140))] if sup_at is not None else [])
    sheet(donor, it, [HC.hand_item('hand', two, t), HC.hand_item('hand2', sup, t2, color=(120, 200, 140))], marks, outdir)
    return row, info


def sheet(donor, it, hands, marks, outdir):
    from PIL import Image
    os.makedirs(outdir, exist_ok=True)
    gi = dict(it); gi.pop('ao', None)   # gunview draws through hudrender.to_local (no angle offsets): all seven donors have none
    a = os.path.join(outdir, donor + '.side.png'); bb = os.path.join(outdir, donor + '.bottom.png')
    gunview.view([gi] + hands, a, 'side', px=5, marks=marks, title='%s hands' % donor)
    gunview.view([gi] + hands, bb, 'bottom', px=5, marks=marks, title='%s hands' % donor)
    A, B = Image.open(a), Image.open(bb)
    O = Image.new('RGB', (max(A.width, B.width), A.height + B.height)); O.paste(A, (0, 0)); O.paste(B, (0, A.height))
    O.save(os.path.join(outdir, donor + '.png')); os.remove(a); os.remove(bb)


def append_rows(rows):
    """new slots at the end of every array of RSQ_HandTable + SlotForDonor lines in a GENERATED block"""
    s = open(TABLE, encoding='utf-8').read()
    # an earlier run's lines stay: the block is a ledger of every fit written, not the last run's
    old = re.search(re.escape(BEGIN) + r'\n(.*?)' + re.escape(END) + r'\n', s, re.S)
    kept = [l for l in old.group(1).splitlines() if l.strip()] if old else []
    refit = {r['donor'] for r in rows}
    kept = [l for l in kept if not any(('"%s"' % d) in l for d in refit)]   # a re-fit replaces its earlier line (the old slot stays in the arrays, unused)
    s = re.sub(re.escape(BEGIN) + r'.*?' + re.escape(END) + r'\n', '', s, flags=re.S)
    n0 = len(re.search(r'static String GunOne\(int i\)\s*\{\s*static const String v\[\] = \{([^}]*)\}', s, re.S).group(1).split(','))
    def arr(fn, name, vals):
        nonlocal s
        pat = r'(static \w+ %s\(int i\)\s*\{(?:(?!\n\t\}).)*?static const \w+ %s\[\] = \{[^}]*)\}' % (fn, name)
        m = re.search(pat, s, re.S); assert m, (fn, name)
        s = s[:m.end(1)] + ', ' + ', '.join(vals) + s[m.end(1):]
    for fn, key in (('GunOne', 'one'), ('GunTwo', 'two'), ('Support', 'sup'), ('Trigger', 'trig')):
        arr(fn, 'v', ['"%s"' % r[key] for r in rows])
    for fn, key in (('GunHook', 'hook'), ('GunRot', 'rot'), ('SupportHook', 'shook'), ('SupportRot', 'srot'), ('SupportPoint', 'spoint'), ('GunHookTwo', 'hook'), ('GunRotTwo', 'rot')):
        for k, ax in enumerate('xyz'): arr(fn, ax, ['%.3f' % r[key][k] for r in rows])
    lines = [BEGIN] + kept + ['\t\tif (donor == "%s")\treturn %d;\t// Ermac %s / support %s, fitted 2026-11-08 (handfit_donors.py)' % (r['donor'], n0 + i, r['two'], r['sup'] or '-') for i, r in enumerate(rows)] + [END]
    m = re.search(r'static int SlotForDonor\(string donor\)\s*\{\s*\n\t\tif \(donor\.Length\(\) == 0\) return 0;\n', s)
    assert m, 'SlotForDonor head not found'
    s = s[:m.end()] + '\n'.join(lines) + '\n' + s[m.end():]   # first in the function: a fit written here wins over an alias or an old row
    open(TABLE, 'w', encoding='utf-8').write(s)
    return n0


def main():
    args = [a for a in sys.argv[1:] if not a.startswith('--')]
    write = '--write' in sys.argv
    rj = next(q for q in (os.path.join(ROOT, 'work', 'gripregions.json'), os.path.join(ROOT, 'tools', 'kit', 'gripregions.json')) if os.path.exists(q))
    regions = json.load(open(rj))['poses']   # tools/kit/gripregions.json: measured 2026-11-08 from Ermac's full hands (RSQ_RustedLegacy src/models/hand)
    ermac = os.environ.get('RSQ_ERMAC') or sys.exit('set RSQ_ERMAC to a folder holding hand/hand.md3 and hand/hand2.md3 (Ermac\'s full hands)')
    outdir = os.path.join(ROOT, 'work', 'handfit')
    rows = []
    for d in args or sorted(TYPE):
        row, info = fit(d, regions, ermac, outdir); print(info)
        if row: rows.append(row)
    if write and rows:
        n0 = append_rows(rows); print('-> %d row(s) appended to %s as slots %d..%d' % (len(rows), os.path.relpath(TABLE, ROOT), n0, n0 + len(rows) - 1))
    print('sheets in', os.path.relpath(outdir, ROOT))


if __name__ == '__main__':
    main()
