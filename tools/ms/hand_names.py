#!/usr/bin/env python3
"""hand_names.py -- give the card-era donors the hand rows their byte-identical 1.x twins already have.

zscript_depot/rsq/handtable.zs (RSQ_HandTable.SlotForDonor) was fitted on the 1.x donor names (MS_brt_*, MS_d64_*,
MS_vplus_*, MS_BD22_*). The shelf now wears the card-era names (MS_BD_*, MS_VP_*, ...), and sources.lock / reload_names.json
record which card mesh IS which 1.x mesh, vertex for vertex (`match: exact`). The same mesh drawn the same way takes the
same hand: this writes, inside SlotForDonor, one GENERATED block of `if (donor == "<card donor>") return <slot>;` for
every card donor that has no row of its own and an exact twin that has one. The reload tables got the same treatment
from tools/ms/reload_names.py on 2026-10-31. Re-run after the hand table or reload_names.json changes.

    python3 tools/ms/hand_names.py          (from anywhere; writes the table in place and prints what it added)
"""
import os, re, json

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
TABLE = os.path.join(ROOT, 'zscript_depot', 'rsq', 'handtable.zs')
NAMES = os.path.join(ROOT, 'reload_names.json')
BEGIN = '\t\t// ---- GENERATED by tools/ms/hand_names.py: card donors on their exact 1.x twins\' hand rows'
END = '\t\t// ---- END GENERATED (hand_names)'
PREFER = ('MS_BD22_', 'MS_brt_', 'MS_d64_', 'MS_vplus_')   # when two twins have rows: the BD22 2.0 fit first


def main():
    ht = open(TABLE, encoding='utf-8').read()
    body = re.sub(re.escape(BEGIN) + r'.*?' + re.escape(END) + r'\n', '', ht, flags=re.S)   # drop an earlier block
    rows = dict(re.findall(r'if \(donor == "(MS_\w+)"\)\s*return (\d+);', body))
    rn = json.load(open(NAMES))
    twins = {}
    for old, v in rn.items():
        if v.get('match') == 'exact': twins.setdefault(v['donor'], []).append(old)
    added = []
    for donor in sorted(twins):
        if donor in rows: continue
        cands = [o for o in twins[donor] if o in rows]
        if not cands: continue
        cands.sort(key=lambda o: next((i for i, p in enumerate(PREFER) if o.startswith(p)), len(PREFER)))
        slot = rows[cands[0]]
        others = [(o, rows[o]) for o in cands[1:] if rows[o] != slot]
        note = ' (other twin%s: %s)' % ('s' if len(others) > 1 else '', ', '.join('%s row %s' % t for t in others)) if others else ''
        added.append('\t\tif (donor == "%s")\treturn %s;\t// = %s, the same mesh (reload_names.json exact)%s' % (donor, slot, cands[0], note))
    block = BEGIN + '\n' + '\n'.join(added) + '\n' + END + '\n'
    # just before SlotForDonor's final `return 0;`
    m = re.search(r'(static int SlotForDonor\(string donor\)\s*\{.*?)(\n\t\treturn 0;\n\t\})', body, re.S)
    assert m, 'SlotForDonor not found'
    out = body[:m.end(1)] + '\n' + block.rstrip('\n') + body[m.end(1):]
    open(TABLE, 'w', encoding='utf-8').write(out)
    print('%d hand row(s) added for card donors:' % len(added))
    for a in added: print(a.strip())


if __name__ == '__main__':
    main()
