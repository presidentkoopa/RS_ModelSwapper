#!/usr/bin/env python3
"""tools_reload_modeldefs.py -- rebuild the reload MODELDEFs (MODELDEF.rsb break-open/revolver, MODELDEF.rsrpump pump)
for the MS 1.5 donors, from the 1.x originals kept in reload_1x/.

Each 1.x section ("// RS real VR reload ...") belongs to one 1.x donor (its first Model line). The section is
written out only when tools_reload_names.py ATTACHED that donor's slot to an MS 1.5 donor (reload_names.json: same
mesh, landing in the same place in the hand). In an attached section:
  * `Model <1.x donor>`              -> `Model <MS 1.5 donor>`
  * Path / Model 0 of the 1.x mesh   -> the card folder / the card mesh (same mesh, same surfaces: 'exact' or
                                        'moved' match only; a re-split card is refused, its surface indices differ)
  * Scale / Offset / ZOffset / angles -> the MS 1.5 donor's own block in `modeldef` (verified to land in the same
                                        place as the 1.x numbers did)
  * SurfaceSkin / FrameIndex lines   -> kept: they are the reload's measured part masks and frames
rsr_clear.png (the see-through skin the masks use) is copied into each card folder that needs it.
Sections not attached are listed and left out. Run tools_reload_names.py first.
"""
import json, os, re, shutil

HERE = os.path.dirname(os.path.abspath(__file__))
PLACE = ('Scale', 'Offset', 'ZOffset', 'AngleOffset', 'PitchOffset', 'RollOffset')


def block(text, name):
    m = re.search(r'Model\s+%s\s*\{(.*?)\n\}' % re.escape(name), text, re.S)
    return m.group(1) if m else None


def slot_of(table, donor):
    t = open(os.path.join('zscript_depot/rsr', table)).read()
    m = re.search(r'if \(donor == "%s"\)\s+return (\d+);' % re.escape(donor), t)
    return int(m.group(1)) if m else None


def main():
    os.chdir(HERE)
    att = json.load(open('reload_names.json'))
    gen = open('modeldef').read()
    # MODELDEF.rsrpump is tools_kit/card_pump.py's now (measured from the cards); not rewritten here
    for lump in ('MODELDEF.rsb', 'MODELDEF.cards'):
        src = open(os.path.join('reload_1x', lump)).read()
        parts = re.split(r'(?=^// RS real VR reload)', src, flags=re.M)
        head, secs = (parts[0], parts[1:]) if not parts[0].startswith('// RS real VR reload') else ('', parts)
        out = ['// GENERATED by tools_reload_modeldefs.py from reload_1x/%s for the MS 1.5 donors. Do not edit.\n' % lump]
        kept, left = [], []
        for sec in secs:
            m = re.search(r'^Model\s+(\w+)', sec, re.M)
            old = m.group(1) if m else None
            a = att.get(old)
            if not a or not a['match'].split()[0] in ('exact', 'moved'):
                left.append('%s (%s)' % (old, 'not attached' if not a else 'card re-split: ' + a['match'])); continue
            new = a['donor']; cdir = os.path.dirname(a['card_mesh']); cfile = os.path.basename(a['card_mesh'])
            # a donor reloads on ONE slot: the first `donor == "<new>"` match in its table. Keep only the section
            # measured for that slot (2.0 has several names on one mesh: MS_BD_Unmaker, MS_brt_Unmaker, ...)
            if slot_of(a['table'], new) != a['slot']:
                left.append('%s (not %s\'s slot)' % (old, new)); continue
            nb = block(gen, new)
            nplace = [l.strip() for l in nb.splitlines() if l.strip().split(' ')[0] in PLACE]
            m0 = re.search(r'Path\s+"([^"]+)"\s*\n\s*Model\s+0\s+"([^"]+)"', sec)
            opath, ofile = m0.group(1), m0.group(2)
            def fix(b):
                lines = []
                for l in b.splitlines():
                    k = l.strip().split(' ')[0] if l.strip() else ''
                    if k in PLACE: continue
                    if l.strip() == 'Path "%s"' % opath: l = '\tPath "%s"' % cdir
                    elif l.strip() == 'Model 0 "%s"' % ofile: l = '\tModel 0 "%s"' % cfile
                    lines.append(l)
                    if k == 'Model' and l.strip().startswith('Model 0'):
                        pass
                # numbers go right before the first FrameIndex / NoInterpolation line
                i = next((j for j, l in enumerate(lines) if l.strip().startswith(('NoInterpolation', 'FrameIndex'))), len(lines))
                return '\n'.join(lines[:i] + ['\t' + p for p in nplace] + lines[i:])
            sec2 = re.sub(r'(Model\s+\w+\s*\{)(.*?)(\n\})', lambda mm: mm.group(1) + fix(mm.group(2)) + mm.group(3), sec, flags=re.S)
            sec2 = re.sub(r'^Model\s+%s\b' % re.escape(old), 'Model %s' % new, sec2, flags=re.M)
            _nc = re.sub(r'//[^\n]*', '', sec2)
            if ('"%s"' % opath) in _nc or ('"%s"' % ofile) in _nc:
                raise SystemExit('%s: a 1.x path is left in the %s section' % (lump, new))
            if 'rsr_clear.png' in sec2 and not os.path.exists(os.path.join(cdir, 'rsr_clear.png')):
                shutil.copy(os.path.join('reload_1x', 'rsr_clear.png'), os.path.join(cdir, 'rsr_clear.png'))
            out.append(sec2); kept.append('%s -> %s' % (old, new))
        if lump == 'MODELDEF.cards':
            # tools_kit/card_mag.py owns MODELDEF.cards (rows measured from the MS 1.5 cards). The 2.0 sections go to
            # MODELDEF.cards2x, only for donors card_mag did not build
            built = set(re.findall(r'^Model\s+(\w+)', open('MODELDEF.cards').read(), re.M))
            keep = [x for x in out[1:] if re.search(r'^Model\s+(\w+)', x, re.M).group(1) not in built]
            kept = [k for k in kept if k.split(' -> ')[1] not in built]
            out = [out[0].replace('reload_1x/MODELDEF.cards', 'reload_1x/MODELDEF.cards (donors card_mag did not build)')] + keep
            lump = 'MODELDEF.cards2x'
        open(lump, 'w').write(''.join(out))
        print('%s: kept %s; left out %s' % (lump, kept or '-', left or '-'))


if __name__ == '__main__':
    main()
