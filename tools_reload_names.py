#!/usr/bin/env python3
"""tools_reload_names.py -- point the reload tables at the MS 1.5 donor names.

The reload tables (zscript_depot/rsr/rsr_guns.ms.zs SlotForDonor, rsb_guns.zs, rsr_pump_guns.zs) map a donor CLASS
NAME to a measured reload slot. They were written for the 1.x donors (MS_BD_BrutalSMG, MS_SuperShotgun, ...);
MS 1.5 generates new names from the cards (MS_BD_Smg, MS_BD_Ssg, ...). This finds, for every 1.x name in those
tables, the 1.x mesh it named (the archived modeldef + mesh on branch archive/pre-cards-2026-10-31) and the card
whose mesh is that same mesh, and adds the card donor's name to the same slot. Nothing is guessed:

  match 'exact'  -- same frame count and frame-0 vertices identical, surface for surface
  match 'bounds' -- same frame count and the whole mesh's frame-0 bounds within 0.05 units (a card mesh whose
                    surfaces were carved or relabelled: same mesh, different surface split)
  no match       -- reported, the slot keeps only its 1.x names

The added lines go in a GENERATED block right after each table's 1.x lines (first match wins in those
functions, so a 1.x name keeps its slot). Report: reload_names.report.md.

    python3 tools_reload_names.py [--archive origin/archive-pre]
"""
import argparse, glob, io, os, re, struct, subprocess, sys
import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, 'tools_kit'))
try:
    from md3read import read_md3_bytes
except Exception:
    read_md3_bytes = None
sys.path.insert(0, os.environ.get('RSQ_DEPOT', '/home/claude/rsq_weapondepot') + '/tools/hqt')
from md3read import read_md3  # noqa: E402

TABLES = ['zscript_depot/rsr/rsr_guns.ms.zs', 'zscript_depot/rsr/rsb_guns.zs', 'zscript_depot/rsr/rsr_pump_guns.zs']
BEGIN, END = '\t\t// ---- GENERATED by tools_reload_names.py: MS 1.5 card donors on the same slots', '\t\t// ---- END GENERATED'


def git(*a):
    return subprocess.run(['git'] + list(a), cwd=HERE, capture_output=True).stdout


def mesh_from_bytes(b):
    p = '/tmp/claude-0/_rn.md3'
    open(p, 'wb').write(b)
    return read_md3(p)


def f0(m): return np.concatenate([s['xyz'][0] for s in m['surfs']])



def block_nums(text, name):
    m = re.search(r'Model\s+%s\s*\{(.*?)\}' % re.escape(name), text, re.S)
    if not m: return None
    b = m.group(1)
    g = lambda k, n: [float(x) for x in (re.search(r'^\s*%s\s+([-\d.]+(?:\s+[-\d.]+)*)' % k, b, re.M | re.I) or [None, ' '.join(['0'] * n)])[1].split()[:n]]
    sc = g('Scale', 3) if re.search(r'^\s*Scale', b, re.M | re.I) else [1.0, 1.0, 1.0]
    return np.array(sc), np.array(g('Offset', 3)), g('ZOffset', 1)[0], [g(k, 1)[0] for k in ('AngleOffset', 'PitchOffset', 'RollOffset')]


def placement_delta(old_md, old_name, new_md, new_name, om, cm):
    """where the mesh's centre lands, 1.x vs 1.5: centre * Scale + Offset + (0,0,ZOffset). Angles must be equal."""
    o = block_nums(old_md, old_name); n = block_nums(new_md, new_name)
    if not o or not n: return 'block missing'
    if o[3] != n[3]: return 'angles differ %s vs %s' % (o[3], n[3])
    # MODELDEF Offset is not on the mesh's axes: Offset y runs along the mesh's x (forward), Offset x along the
    # mesh's -y, z is z (the HUD model is turned -90 about up). The 1.x re-origin tool used the same rule
    # (MS_BD_Rifle: mesh moved +39.52 x, compensated with Offset y -39.516), and with it 1.x == 1.5 there.
    def land(m, B):
        c = (f0(m).min(0) + f0(m).max(0)) / 2
        sc, of, zo = B[0], B[1], B[2]
        return np.array([sc[0] * c[0] + of[1], sc[1] * c[1] - of[0], sc[2] * c[2] + of[2] + zo])
    po = land(om, o); pn = land(cm, n)
    d = pn - po
    return '%s (%.2f)' % (np.round(d, 2).tolist(), float(np.linalg.norm(d)))

def main():
    ap = argparse.ArgumentParser(); ap.add_argument('--archive', default='origin/ms20', help='the tree the reload tables were measured on (2.0 branch; 1.x: origin/archive-pre)')
    a = ap.parse_args(); os.chdir(HERE)
    # every MODELDEF lump at the source tree's root (1.x: modeldef; 2.0: MODELDEF.bd22 / .cards / .aliens / ...)
    roots = [n for n in git('ls-tree', '--name-only', a.archive).decode().splitlines() if re.match(r'(?i)^modeldef(\.|$)', n) and 'before' not in n]
    md = '\n'.join(git('show', a.archive + ':' + n).decode('latin-1') for n in roots)
    old = {}
    for m in re.finditer(r'Model\s+(\w+)\s*\{(.*?)\}', md, re.S):
        p = re.search(r'Path\s+"([^"]+)"', m.group(2)); f = re.search(r'Model\s+0\s+"([^"]+)"', m.group(2))
        if p and f: old.setdefault(m.group(1), (p.group(1).strip('/') + '/' + f.group(1)))
    tree = {n.lower(): n for n in git('ls-tree', '-r', '--name-only', a.archive).decode().splitlines()}
    cards = []
    for c in sorted(glob.glob('cards/*/*/*.card')):
        if '.blend' in c or '/_' in c: continue
        mp = c[:-5] + '.md3'
        if os.path.exists(mp): cards.append((c, read_md3(mp)))
    gen = open('modeldef').read()
    card_donor = {}
    for m in re.finditer(r'Model (MS_\w+)\s*\{.*?Path "([^"]+)"\s*Model 0 "([^"]+)"', gen, re.S):
        card_donor[m.group(2) + '/' + m.group(3)] = m.group(1)
    remeasure = {}
    attached = {}
    rep = ['# Reload slots -> MS 1.5 donor names', '', '| table | slot | 1.x donor | 1.x mesh | match | MS 1.5 donor | in-hand shift 1.x -> 1.5 (MODELDEF units) |', '|---|---|---|---|---|---|---|']
    for tbl in TABLES:
        t = open(tbl).read()
        t = re.sub(re.escape(BEGIN) + r'.*?' + re.escape(END) + r'\n', '', t, flags=re.S)
        pairs = re.findall(r'if \(donor == "(\w+)"\)\s+return (\d+);', t)
        add = []; have = {d for d, _ in pairs}; cand = {}
        for d, slot in pairs:
            path = old.get(d)
            src = tree.get(path.lower()) if path else None
            if not src:
                rep.append('| %s | %s | %s | %s | 1.x mesh not in archive | - |' % (os.path.basename(tbl), slot, d, path)); continue
            om = mesh_from_bytes(git('show', a.archive + ':' + src))
            hit = None
            for c, cm in cards:
                if cm['nframes'] != om['nframes']: continue
                if len(cm['surfs']) == len(om['surfs']) and all(np.array_equal(x['xyz'][0], y['xyz'][0]) for x, y in zip(cm['surfs'], om['surfs'])):
                    hit = (c, 'exact'); break
            if not hit:
                # the same mesh moved: 1.x baked its placement into the vertices (same surfaces, same counts, every
                # frame-0 vertex shifted by one vector)
                for c, cm in cards:
                    if cm['nframes'] != om['nframes'] or len(cm['surfs']) != len(om['surfs']): continue
                    if any(x['xyz'].shape != y['xyz'].shape for x, y in zip(cm['surfs'], om['surfs'])): continue
                    dv = f0(cm) - f0(om)
                    if np.abs(dv - dv.mean(0)).max() < 0.05:
                        hit = (c, 'moved %s' % np.round(dv.mean(0), 2).tolist()); break
            if not hit:
                # moved AND re-split (a card re-carved from the source md3): same frame count, same whole-mesh
                # extent in every frame-0 axis
                ov = f0(om); oe = ov.max(0) - ov.min(0)
                for c, cm in cards:
                    if cm['nframes'] != om['nframes']: continue
                    cv = f0(cm)
                    if np.abs((cv.max(0) - cv.min(0)) - oe).max() < 0.05:
                        hit = (c, 'moved+resplit %s' % np.round(cv.min(0) - ov.min(0), 2).tolist()); break
            if not hit:
                ov = f0(om)
                for c, cm in cards:
                    if cm['nframes'] != om['nframes']: continue
                    cv = f0(cm)
                    if np.abs(cv.min(0) - ov.min(0)).max() < 0.05 and np.abs(cv.max(0) - ov.max(0)).max() < 0.05:
                        hit = (c, 'bounds'); break
            if hit:
                key = os.path.dirname(hit[0]) + '/' + os.path.basename(hit[0])[:-5] + '.md3'
                nd = card_donor.get(key)
                place = placement_delta(md, d, gen, nd, om, dict(cards)[hit[0]]) if nd else '-'
                rep.append('| %s | %s | %s | %s | %s | %s | %s |' % (os.path.basename(tbl), slot, d, src, hit[1], nd or '(card not generated)', place))
                ok = place.endswith('(0.00)') or bool(re.search(r'\((0\.[0-4]\d)\)$', place))
                if nd and ok:
                    attached.setdefault(d, {'donor': nd, 'card_mesh': key, 'match': hit[1], 'table': os.path.basename(tbl), 'slot': int(slot)})
                if nd and ok:
                    cand.setdefault(nd, []).append((slot, d))
                elif nd and not ok:
                    remeasure.setdefault((os.path.basename(tbl), slot, nd), []).append('%s: %s' % (d, place))
            else:
                rep.append('| %s | %s | %s | %s | no card mesh matches | - |' % (os.path.basename(tbl), slot, d, src))
        # one slot per new donor: the one whose reload layers exist (a section in reload_1x/ lumps), else the first
        layered = set()
        for lump in glob.glob(os.path.join(HERE, 'reload_1x', 'MODELDEF.*')):
            layered |= set(re.findall(r'^// RS real VR reload[^\n]*\n(?:[^\n]*\n)*?Model\s+(\w+)', open(lump).read(), re.M))
        for nd, lst in cand.items():
            if nd in have: continue
            pick = next((sl for sl, d in lst if d in layered), lst[0][0])
            add.append((nd, pick)); have.add(nd)
        if add:
            last = list(re.finditer(r'\t\tif \(donor == "\w+"\)\s+return \d+;\n', t))[-1]
            block = BEGIN + '\n' + ''.join('\t\tif (donor == "%s")\treturn %s;\n' % x for x in add) + END + '\n'
            t = t[:last.end()] + block + t[last.end():]
        open(tbl, 'w').write(t)
        print('%s: %d 1.x names, %d MS 1.5 names added' % (tbl, len(pairs), len(add)))
    # a 1.5 donor that lands on ANY 1.x name of its slot exactly was added; drop it from the re-measure list
    for tbl in TABLES:
        t = open(tbl).read()
        for k in list(remeasure):
            if k[0] == os.path.basename(tbl) and ('donor == "%s"' % k[2]) in t: remeasure.pop(k)
    rep += ['', '## Not attached: lands elsewhere than its slot was measured (re-measure the reload for the 1.5 placement)', '']
    rep += ['- %s slot %s %s -- %s' % (k[0], k[1], k[2], '; '.join(v)) for k, v in sorted(remeasure.items())]
    import json
    json.dump(attached, open('reload_names.json', 'w'), indent=1, sort_keys=True)
    open('reload_names.report.md', 'w').write('\n'.join(rep) + '\n')
    print('not attached (re-measure):', ', '.join(sorted({k[2] for k in remeasure})))


if __name__ == '__main__':
    main()
