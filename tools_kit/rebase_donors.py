"""rebase_donors.py -- draw each card-measured donor where its reload row and hands were made for.

    python -B tools_kit/rebase_donors.py [--dry] [--only MS_A,MS_B] [--max-cm N]

placement_audit.py shows the older donors (reload slots 3-30) drawing their gun up to 137 cm from
where their reload row and hand row put it: the rows were generated by card2quest.py at the card's
placement (its `palm` on the Quest grip reference) and rest frame, the hands were fitted by
handfit_cards.py at that same placement, and several donors share one row while each kept the
placement it was imported with. A hand cannot reach a magazine well a metre from the gun.

For every donor whose mesh IS the card's mesh (same content, or the same re-centred: a pure
translation), this rewrites its donor block to the ROW's Scale and Offset (plus the re-centring
shift, solved through card2quest.to_flu so the mesh lands exactly where the row's would) and its
rest frame to the card's (the block's anchor FrameIndex and the shelf row's rest-frame field; a
shelf row keeps its index, so no saved pick moves). Rows, hands and drawing then agree, which is
how the BD22Q and Aliens lifts work. Donors with no card, another mesh (a _wm rebuild) or a reload
row that is not card-derived (the lifted sets', slots 1, 2, 17 and 31+) are not touched.
Re-run tools_kit/gunmoves_ms.py after: the pivots follow the placement.
"""
import os, re, sys
import numpy as np
HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, HERE)
import placement_audit as PA
import card2quest as C

LIFTED_SLOTS = {1, 2, 17}          # rows from a set (lift_aliens.py); 31+ are BD22Q's / the Aliens set's


def solve_offset(card_mesh, donor_mesh, scale, row_off, cf, df):
    """the Offset that puts donor_mesh (frame df) where card_mesh (frame cf) is at (scale, row_off)"""
    a = C.to_flu(PA.frame0(card_mesh, cf), scale, row_off).mean(0)
    b0 = PA.frame0(donor_mesh, df)
    base = C.to_flu(b0, scale, (0, 0, 0)).mean(0)
    J = np.stack([C.to_flu(b0, scale, e).mean(0) - base for e in np.eye(3)], 1)
    off = np.linalg.solve(J, a - base)
    err = np.abs(C.to_flu(b0, scale, off) - C.to_flu(PA.frame0(card_mesh, cf), scale, row_off)).max()
    return off, err


def main(dry, only, max_cm):
    rows = PA.audit()
    md_p = os.path.join(ROOT, 'modeldef'); md = open(md_p, encoding='utf-8', errors='replace').read()
    sh_p = os.path.join(ROOT, 'zscript/RS_ForeignModels.zs'); sh = open(sh_p).read()
    an_p = os.path.join(ROOT, 'zscript/RS_ForeignAnim.zs'); an = open(an_p).read()
    cards = {w['cls']: w for w in C.load_cards(ROOT)}
    done = 0
    rsr = open(os.path.join(ROOT, 'zscript_depot/rsr/rsr_guns.ms.zs')).read()
    import lift_common as L
    for r in rows:
        d = r['donor']
        if only and d not in only:
            continue
        if r['slot'] in LIFTED_SLOTS or r['slot'] > 30:
            continue
        # the row was generated from ONE card -- its NoMag names that donor. Every donor of the
        # slot is placed against THAT card's mesh and rest frame, not its own card's.
        src = L.read_row(rsr, r['slot'])['NoMag'][1].strip('"').replace('RSR_NoMag_', '')
        sw = cards.get(src)
        cmesh = C.model_path(ROOT, sw) if sw else None
        if not cmesh or not os.path.exists(cmesh) or '_wm' in os.path.basename(cmesh).lower():
            print('%-26s slot %2d: row from %s (%s) -- not a shipped real mesh, left' % (d, r['slot'], src, os.path.basename(cmesh) if cmesh else 'no card')); continue
        bm = re.search(r'^Model\s+%s\s*\n\{(.*?)^\}' % d, md, re.S | re.M)
        body = bm.group(1)
        dmesh = os.path.join(ROOT, re.search(r'Path\s+"([^"]+)"', body).group(1), re.search(r'Model\s+0\s+"([^"]+)"', body).group(1))
        a, b = PA.frame0(cmesh), PA.frame0(dmesh)
        if a.shape != b.shape or np.ptp(b - a, 0).max() > 1e-3:
            print('%-26s slot %2d: its mesh is not %s\'s (%s) -- left' % (d, r['slot'], src, os.path.basename(cmesh))); continue
        cf = C.rest_frame(sw, cmesh)
        off, err = solve_offset(cmesh, dmesh, r['row_scale'], r['row_off'], cf, cf)
        if err > 0.05:
            print('%-26s cannot place exactly (residual %.3f cm) -- left' % (d, err)); continue
        moved = np.abs(C.to_flu(b, r['donor_scale'], r['donor_off']) - C.to_flu(b, r['row_scale'], off)).max()
        if max_cm is not None and moved > max_cm:
            print('%-26s %6.1f cm -- over --max-cm, left' % (d, moved)); continue
        r['dpos_cm'] = moved
        nb = re.sub(r'^[ \t]*ZOffset[^\n]*\n', '', body, flags=re.M)
        nb = re.sub(r'^([ \t]*Scale\s+)[^\n]*', r'\g<1>%s' % ' '.join('%g' % v for v in r['row_scale']), nb, count=1, flags=re.M)
        nb = re.sub(r'^([ \t]*Offset\s+)[^\n]*', r'\g<1>%s' % ' '.join('%.3f' % v for v in off), nb, count=1, flags=re.M)
        # the rest frame: the block's anchor line (the first FrameIndex that is not MSBL)
        fm = next(m for m in re.finditer(r'^([ \t]*FrameIndex\s+(\w{4})\s+(\S)\s+0\s+)(\d+)', nb, re.M) if m.group(2) != 'MSBL')
        anchor, letter = fm.group(2), fm.group(3)
        nb = nb[:fm.start(4)] + str(cf) + nb[fm.end(4):]
        note = '\t// placement + rest frame: its reload row\'s and hand row\'s (tools_kit/rebase_donors.py; was %s, frame %s)\n' % (
            ' '.join('%g' % v for v in r['donor_off']), r['donor_frame'])
        if 'rebase_donors.py' not in nb:
            nb = '\n' + note + nb.lstrip('\n')
        md = md[:bm.start(1)] + nb + md[bm.end(1):]
        sh = re.sub(r'("\w+\|%s\|\w{4}\|\d+\|)\d+(\|\d+")' % d, r'\g<1>%d\2' % cf, sh)
        an = re.sub(r'("%s\|ready\|)\d+(@)' % d, r'\g<1>%d\2' % cf, an)
        print('%-26s slot %2d  %6.1f cm off -> row placement %s, frame %s -> %d (residual %.4f)'
              % (d, r['slot'], r['dpos_cm'], np.round(off, 3).tolist(), r['donor_frame'], cf, err))
        done += 1
    if not dry:
        for p, t in ((md_p, md), (sh_p, sh), (an_p, an)):
            open(p, 'w', encoding='utf-8', newline='\n').write(t)
    print('%d donors %s' % (done, 'would move' if dry else 'moved'))


if __name__ == '__main__':
    if '--i-checked-the-hands' not in sys.argv:
        sys.exit('MEASURED WRONG (2026-10-25): the hand rows fit the donor placement, not the row\'s -- moving donors pulls guns out of the hands. Use regen_rows.py. Kept as the record; pass --i-checked-the-hands to run anyway.')
    only = set(sys.argv[sys.argv.index('--only') + 1].split(',')) if '--only' in sys.argv else None
    mx = float(sys.argv[sys.argv.index('--max-cm') + 1]) if '--max-cm' in sys.argv else None
    main('--dry' in sys.argv, only, mx)
