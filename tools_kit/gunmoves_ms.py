"""gunmoves_ms.py -- RSQ_GunMoves Pivot / Mirrored / Blends for EVERY hand slot, from its donor's own block.

    python -B tools_kit/gunmoves_ms.py [--check <RS_Brutal22WeaponsQ/src> <RSQ_WeaponDepot/sets/aliens/src>]

zscript_depot/rsq/gunmoves.zs shipped as BD22Q's own table: 26 rows by BD22 GUN CLASS, read by
ModelSwapper's hand slot, so each slot took the row of whichever BD22 gun had the same number
(and slots past 26 none). Pivot is where the gun model turns when its layer moves (bob, raise,
lower, Offset kicks); the hands turn with it about that point, so a wrong pivot puts the hand off
the grip whenever the gun moves. (Seen 2026-10-25: MS_AE_Pistol's hand beside the gun; the BD22
pistol's hand off its grip.)

Pivot is not measured from a mesh: it is the donor block's placement against the hand models'
(the kit's rsq_gunmoves_gen.py maths, as the Aliens set's ae_gunmoves_gen.py copies it):

    Pivot    = diag(-1, 1, 1) . (Offset x, Offset z, Offset y) - (0, -10, -24)
               (ZOffset IS Offset's z -- the engine's one zoffset field; the last line wins)
    Mirrored = Scale x > 0
    Blends   = the block has no NoInterpolation

so every donor gets its own, from the block it is drawn with. --check recomputes the lifted
donors' rows and compares them with the source sets' own gunmoves.zs (the formula must give
back exactly what BD22Q and the Aliens set ship).

Frame() is left as it is: it is keyed by the source mod's own sprite names, which a foreign
weapon never shows, so it never fires for a donor.
"""
import os, re, sys
import numpy as np
HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, HERE)
from lift_common import donor_blocks
D = np.diag([-1.0, 1.0, 1.0])
O_H = np.array([0.0, -10.0, -24.0])


def placement(body):
    def nums(key):
        m = re.search(r'^[ \t]*%s\s+([-\d.eE]+(?:\s+[-\d.eE]+)*)' % key, body, re.M | re.I)
        return [float(x) for x in m.group(1).split()] if m else None
    scale = nums('Scale') or [1.0, 1.0, 1.0]
    off = nums('Offset') or [0.0, 0.0, 0.0]
    off = list(off) + [0.0] * (3 - len(off))
    z = nums('ZOffset')
    if z:
        off[2] = z[0]
    nointerp = re.search(r'^[ \t]*NoInterpolation\b', body, re.M | re.I) is not None
    return scale, off, nointerp


def row_for(body):
    scale, off, nointerp = placement(body)
    pivot = D @ np.array([off[0], off[2], off[1]]) - O_H
    return pivot, scale[0] > 0, not nointerp


def slots():
    h = open(os.path.join(ROOT, 'zscript_depot/rsq/handtable.zs')).read()
    return {d: int(s) for d, s in re.findall(r'donor == "(\w+)"\)\s*return (\d+);', h)}


def table(fn, typ, vals):
    return '\t\tstatic const %s v[] = { %s };' % (typ, ', '.join(vals))


def main():
    blocks = donor_blocks(open(os.path.join(ROOT, 'modeldef'), encoding='utf-8', errors='replace').read())
    sl = slots(); n = max(sl.values())
    piv = [np.zeros(3)] * (n + 1); mir = [0] * (n + 1); ble = [0] * (n + 1)
    for d, s in sorted(sl.items(), key=lambda kv: kv[1]):
        if d not in blocks:
            print('%-24s slot %2d: no donor block -- left 0' % (d, s)); continue
        p, m, b = row_for(blocks[d])
        piv[s], mir[s], ble[s] = p, int(m), int(b)
    p = os.path.join(ROOT, 'zscript_depot/rsq/gunmoves.zs'); t = open(p).read()
    t = re.sub(r'(Pivot\(int i\)\s*\{\s*)static const double v\[\] = \{.*?\};',
               lambda m: m.group(1) + 'static const double v[] = { %s };' % ', '.join('%.3f, %.3f, %.3f' % tuple(0.0 if abs(x) < 5e-4 else x for x in v) for v in piv), t, count=1, flags=re.S)
    t = re.sub(r'(Mirrored\(int i\)\s*\{\s*)static const int v\[\] = \{.*?\};',
               lambda m: m.group(1) + 'static const int v[] = { %s };' % ', '.join(map(str, mir)), t, count=1, flags=re.S)
    t = re.sub(r'(Blends\(int i\)\s*\{\s*)static const int v\[\] = \{.*?\};',
               lambda m: m.group(1) + 'static const int v[] = { %s };' % ', '.join(map(str, ble)), t, count=1, flags=re.S)
    head = ('// Pivot / Mirrored / Blends: one per ModelSwapper HAND SLOT, from the donor\'s own MODELDEF block\n'
            '// (tools_kit/gunmoves_ms.py -- do not edit by hand). Frame(): BD22Q\'s, keyed by its own sprites.\n')
    t = re.sub(r'^// Pivot / Mirrored / Blends.*?\n.*?\n', '', t, count=1, flags=re.M)
    t = re.sub(r'^// Pivot / Mirrored / Blends of the LIFTED slots.*?\n.*?\n', '', t, count=1, flags=re.M)
    t = t.replace('// generated by rsq_gunmoves_gen.py (bd22) -- do not edit by hand\n',
                  '// generated by rsq_gunmoves_gen.py (bd22) -- do not edit by hand\n' + head, 1)
    open(p, 'w', newline='\n').write(t)
    print('%d slots written (max %d)' % (len(sl), n))
    return blocks, sl


def check(bd22, aliens):
    import lift_bd22 as B, lift_aliens as A
    blocks = donor_blocks(open(os.path.join(ROOT, 'modeldef'), encoding='utf-8', errors='replace').read())
    def src_rows(path):
        t = open(os.path.join(path, 'zscript/rsq/gunmoves.zs')).read()
        pv = [float(x) for x in re.search(r'Pivot\(int i\).*?v\[\] = \{(.*?)\};', t, re.S).group(1).split(',')]
        mi = [int(x) for x in re.search(r'Mirrored\(int i\).*?v\[\] = \{(.*?)\};', t, re.S).group(1).split(',')]
        hi = A.tc_index(open(os.path.join(path, 'zscript/rsq/handtable.zs')).read())
        return pv, mi, hi
    bad = 0
    for name, path, pairs in (('BD22Q', bd22, [(B.donor(c), c) for c in B.GUNS]),
                              ('Aliens', aliens, [(d, c) for c, (_, _, ds) in A.GUNS.items() for d in ds])):
        pv, mi, hi = src_rows(path)
        for d, c in pairs:
            if d not in blocks or c not in hi:
                continue
            i = hi[c]; want = np.array(pv[3 * i:3 * i + 3]); got, m, _ = row_for(blocks[d])
            ok = np.allclose(want, got, atol=0.01) and bool(mi[i]) == m
            note = '' if ok else ('  (re-centred copy: its own origin)' if d.startswith('MS_AE_') else '  MISMATCH')
            bad += 0 if ok or d.startswith('MS_AE_') else 1
            print('%-6s %-24s source %s  computed %s%s' % (name, d, np.round(want, 3), np.round(got, 3), note))
    if bad:
        sys.exit('%d lifted donors do not reproduce their set\'s pivot' % bad)


if __name__ == '__main__':
    if '--check' in sys.argv:
        i = sys.argv.index('--check'); check(sys.argv[i + 1], sys.argv[i + 2])
    else:
        main()
