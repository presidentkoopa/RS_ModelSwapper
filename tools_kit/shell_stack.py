"""shell_stack.py -- where the 2nd, 3rd and 4th shell sit in the off hand (Options: Shells per grab).

    python3 -B tools_kit/shell_stack.py            writes zscript_depot/rsr/rsp_stack.ms.zs

Measured, nothing typed in:
  * Ermac's one-shell hold (models/ammo_hand/ammo_hand.md3 frame 1, the hold layer 2210 draws in)
    and his shell (shot_shell.md3), in the off controller's frame (his MODELDEF.rsq block: Scale -1 1 1,
    Offset 0 -24 -10), cm, F L U.
  * The extra shells lie beside the held one, parallel to it, touching (centre spacing = the drawn
    shell's diameter). The direction is searched round the shell's axis in 5 degree steps; kept is
    the one where shells 2, 3 and 4 each pass into the hand mesh NO deeper than the held shell itself
    does (its own count is the baseline) and EACH is in contact with the hand (hand vertices within
    1 cm of its skin) -- the one whose least-held shell is held the most. (The first cut asked only
    shell 2 to touch; its render showed shells 3 and 4 standing out of the fist in the air.)
  * Spacing per pump slot: the diameter of that gun's own shell surface, at the frame and scale its
    MODELDEF block draws it (MODELDEF.rsrpump / .bd22 / .aliens, the RSQ_Hands shell blocks), since
    that is the shell drawn in the hand.
"""
import os, sys, math
import numpy as np
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from rgeo import load_md3, to_flu, pca

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
HS, HO = (-1.0, 1.0, 1.0), (0.0, -24.0, -10.0)
HOLD_FRAME = 1
# the pump slots' shells, as their RSQ_Hands blocks draw them (slot: mesh, surface, frame, scale)
SHELLS = {
    1: ('models/hud/Shotgun/shotgun.md3', 2, 12, 1.35),           # MODELDEF.rsrpump, FrameIndex RQUQ C 0 12
    2: ('models/depot_bd/bd/ShotGun/Shotgun.md3', 2, 4, 1.0),       # MODELDEF.bd22,    FrameIndex RQUP C 0 4
    3: ('models/alien/shotgun/m37a2.md3', 3, 23, 1.1),              # MODELDEF.aliens,  FrameIndex RSHP C 0 23
}


def axis_mid(p):
    c, vt, _ = pca(p)
    a = vt[0]
    t = (p - c) @ a
    return c + a * ((t.max() + t.min()) / 2), a, float(np.ptp(t))


def radius(p, mid, a):
    r = p - mid
    return float(np.linalg.norm(r - np.outer(r @ a, a), axis=1).max())


def main():
    sh = to_flu(load_md3(os.path.join(ROOT, 'models/ammo_hand/shot_shell.md3'))[0]['xyz'][0], HS, HO)
    mid, a, L = axis_mid(sh)
    R = radius(sh, mid, a)
    hand = to_flu(load_md3(os.path.join(ROOT, 'models/ammo_hand/ammo_hand.md3'))[0]['xyz'][HOLD_FRAME], HS, HO)
    u = np.cross(a, [0, 0, 1.0]); u /= np.linalg.norm(u)
    w = np.cross(a, u)

    def inside(c, rr):
        q = hand - c
        ta = q @ a
        rp = np.linalg.norm(q - np.outer(ta, a), axis=1)
        return int(np.sum((np.abs(ta) <= L / 2) & (rp < rr)))

    base = inside(mid, R)
    best = None
    for deg in range(0, 360, 5):
        e = math.cos(math.radians(deg)) * u + math.sin(math.radians(deg)) * w
        clip = [inside(mid + k * 2 * R * e, R) for k in (1, 2, 3)]
        touches = [inside(mid + k * 2 * R * e, R + 1.0) - c for k, c in zip((1, 2, 3), clip)]
        touch = min(touches)
        # every added shell held: in contact with the hand (vertices within 1 cm of its skin), and none
        # deeper in the hand than the held shell itself is. Best: the least-held shell held the most.
        if max(clip) <= base and touch > 0:
            key = (-touch, sum(clip))
            if best is None or key < best[0]:
                best = (key, deg, e, clip, touches)
    if best is None:
        sys.exit('no clear stack direction found')
    _, deg, e, clip, touch = best
    print('Ermac shell: diameter %.3f cm, length %.2f cm; the held shell passes %d hand vertices' % (2 * R, L, base))
    print('stack: %d deg about the shell axis, dir (F L U) %s; shells 2-4 pass %s hand vertices, touch %s'
          % (deg, np.round(e, 4), clip, touch))
    dia = {}
    for i, (m, s, f, sc) in SHELLS.items():
        p = load_md3(os.path.join(ROOT, m))[s]['xyz'][f] * sc
        pm, pa, _ = axis_mid(p)
        dia[i] = 2 * radius(p, pm, pa)
        print('slot %d: %s surface %d frame %d scale %g: shell diameter %.3f cm' % (i, m, s, f, sc, dia[i]))
    out = os.path.join(ROOT, 'zscript_depot/rsr/rsp_stack.ms.zs')
    rows = '\n'.join('\t\tcase %d:\treturn %.3f;' % (i, dia[i]) for i in sorted(dia))
    open(out, 'w').write('''// generated by tools_kit/shell_stack.py -- do not edit by hand
// Options, VR Reload: Shells per grab (ms_shell_grab, 1-4). Where the 2nd-4th shell lie in the off
// hand (layers 2211-2213, rsr/rsr_pump.zs): beside the held one, parallel, touching. Direction in the
// off controller's frame (cm, F L U), searched on Ermac's one-shell hold (ammo_hand.md3 frame %d) so
// no added shell passes into the hand deeper than the held shell does (%d deg about its axis).
class RSP_Stack abstract
{
	clearscope static Vector3 Dir() { return (%.4f, %.4f, %.4f); }

	// the spacing: the diameter of that gun's own shell, as its hand block draws it (cm)
	clearscope static double Spacing(int i)
	{
		switch (i)
		{
%s
		}
		return %.3f;
	}
}
''' % (HOLD_FRAME, deg, e[0], e[1], e[2], rows, 2 * R))
    print('wrote', out)


if __name__ == '__main__':
    main()
