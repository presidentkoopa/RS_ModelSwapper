"""gunmoves_sync.py -- give every LIFTED hand slot its source set's own RSQ_GunMoves row.

    python -B tools_kit/gunmoves_sync.py <RS_Brutal22WeaponsQ/src> <RSQ_WeaponDepot/sets/aliens/src>

zscript_depot/rsq/gunmoves.zs is BD22Q's own table, byte for byte: 26 rows, one per BD22 GUN
CLASS. ModelSwapper reads it by ITS hand slot (RSQ_HandTable.Index = the donor's slot), so every
slot got the row of whichever BD22 gun had the same number, and slots past 26 got nothing.
Pivot is where the gun model turns when its layer is offset (bob, raise, lower, kick) and the
hands turn with it about that point -- a wrong pivot puts the hand off the gun whenever the
layer moves (found 2026-10-25: MS_AE_Pistol, slot 2, took BD22 gun 2's pivot 0 5 24 and its
hand sat beside the gun; MS_alien_pistol, slot 27, ran off the end; the Aliens set's M4A3 is
0 2 -5).

For each donor a lift put on the shelf, the slot's Pivot / Mirrored / Blends become the SOURCE
set's row for that gun (BD22Q's gunmoves.zs by BD22 class, the Aliens set's by Aliens class).
Frame() is not touched: it is keyed by the source mod's own sprite names, which a foreign
weapon never shows. Slots no lift owns keep what they had (see HANDOFF: still BD22's rows by
accident -- they need their own source).
"""
import os, re, sys
HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, HERE)
import rsr_table as T
import lift_bd22 as B
import lift_aliens as A


def index_of(text):
    f = next(f for f in T.functions(text) if f['name'] == 'Index')
    return {c: int(n) for c, n in re.findall(r"w is '(\w+)'\)\s*return (\d+);", f['body'])}


def arr(text, fn):
    m = re.search(r'%s\(int i\)\s*\{\s*static const (\w+) v\[\] = \{(.*?)\};' % fn, text, re.S)
    return m.group(1), [x.strip() for x in m.group(2).split(',')], m


def set_item(text, fn, idx, vals, width):
    typ, items, m = arr(text, fn)
    default = '0.000' if typ == 'double' else '0'
    need = (idx + 1) * width
    items += [default] * max(0, need - len(items))
    items[idx * width:idx * width + width] = vals
    return text[:m.start(2)] + ' ' + ', '.join(items) + ' ' + text[m.end(2):]


def row(text, i):
    _, p, _ = arr(text, 'Pivot'); _, mi, _ = arr(text, 'Mirrored'); _, bl, _ = arr(text, 'Blends')
    pv = p[3 * i:3 * i + 3] if 3 * i + 2 < len(p) else ['0.000'] * 3
    return pv, (mi[i] if i < len(mi) else '0'), (bl[i] if i < len(bl) else '0')


def main(bd22, aliens):
    p = os.path.join(ROOT, 'zscript_depot/rsq/gunmoves.zs'); t = open(p).read()
    hand = open(os.path.join(ROOT, 'zscript_depot/rsq/handtable.zs')).read()
    jobs = []
    b_gm = open(os.path.join(bd22, 'zscript/rsq/gunmoves.zs')).read()
    b_idx = index_of(open(os.path.join(bd22, 'zscript/rsq/handtable.zs')).read())
    for cls in B.GUNS:
        jobs.append(('BD22Q', B.donor(cls), cls, b_gm, b_idx.get(cls)))
    a_gm = open(os.path.join(aliens, 'zscript/rsq/gunmoves.zs')).read()
    a_idx = index_of(open(os.path.join(aliens, 'zscript/rsq/handtable.zs')).read())
    for cls, (_, _, donors) in A.GUNS.items():
        for d in donors:
            jobs.append(('Aliens', d, cls, a_gm, a_idx.get(cls)))
    for setname, d, cls, src, si in jobs:
        slot = A.slot_of(hand, d)
        if slot is None or si is None:
            print('%-20s no hand slot / no %s row -- skipped' % (d, setname)); continue
        pv, mi, bl = row(src, si)
        t = set_item(t, 'Pivot', slot, pv, 3)
        t = set_item(t, 'Mirrored', slot, [mi], 1)
        t = set_item(t, 'Blends', slot, [bl], 1)
        print('%-20s hand slot %2d <- %s %s (%d): pivot %s mirrored %s blends %s' % (d, slot, setname, cls, si, ' '.join(pv), mi, bl))
    if 'gunmoves_sync.py' not in t:
        t = t.replace('// generated by rsq_gunmoves_gen.py (bd22) -- do not edit by hand',
                      '// generated by rsq_gunmoves_gen.py (bd22) -- do not edit by hand\n'
                      '// Pivot / Mirrored / Blends of the LIFTED slots re-keyed per ModelSwapper hand slot by\n'
                      '// tools_kit/gunmoves_sync.py (each from its own set\'s table); the rest are still BD22\'s by number.', 1)
    open(p, 'w', newline='\n').write(t)


if __name__ == '__main__':
    if len(sys.argv) < 3:
        sys.exit(__doc__)
    main(sys.argv[1], sys.argv[2])
