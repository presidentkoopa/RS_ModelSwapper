"""Fit Ermac's hands onto every model on the ModelSwapper shelf that has a card.

handfit_cards.py does the fitting and this does not change one number of it: its
method is the kit's own (hands/HAND_FITTING.md, align_free.py, fitall_free.py) --
keep Ermac's posed hand, and find the TRANSLATION that puts its measured gripping
face (gripregions.json) onto the gun by ICP, anchored in a tight window round the
card's own `palm` for the gun hand and `supportat` for the support hand.

What this driver supplies is what handfit_cards cannot know, and it is the same
two things gen_modelswapper had to supply for the reload:

  THERE IS NO SET.  handfit_cards walks genpack.set_members over a standalone
    build's MODELDEF.wmq. ModelSwapper has no sets and no genpack build -- it has
    a shelf, and its own `modeldef` holds every donor's Path, Model, Scale, Offset
    and rest frame. So the walk is over the shelf.

  THE WEAPON IS NOT OURS.  RSQ_HandTable.Index(Weapon) matches on the weapon's
    CLASS, which is right for a standalone pack whose weapon IS the gun. Here the
    weapon belongs to whatever mod is loaded and only its MODEL is ours, so the
    hand pose has to come from the model in hand -- the same donor lookup the
    reload table uses, reading the same two cvars RS_ForeignModelHandler
    publishes. One gun, one place that answers "which gun is this".

A model is fitted when its card carries a grip palm. Everything else keeps index
0, which is the hands off -- the same as today, for that model only.

usage: python -B tools_kit/run_handfit.py [out.zs]
       default out: zscript_depot/rsq/handtable.zs
"""
import os, re, sys, json
import numpy as np

ROOT = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..'))
sys.path.insert(0, os.path.join(ROOT, 'tools_kit'))
sys.dont_write_bytecode = True

import card2quest as c2q
import genpack as gp
import handfit_cards as hf
import run_modelswapper as rms

OUT = os.path.join(ROOT, 'zscript_depot', 'rsq', 'handtable.zs')
SHEETS = os.path.join(ROOT, '_handfit')
REPORT = os.path.join(ROOT, 'handfit_report.json')


def shelf_blocks():
    """donor model -> everything its modeldef block says about how it is drawn"""
    md = open(os.path.join(ROOT, 'modeldef'), encoding='utf-8', errors='replace').read()
    out = {}
    for m in re.finditer(r'(?ms)^Model\s+(\S+)\s*\r?\n\{(.*?)^\}', md):
        name, b = m.group(1), m.group(2)
        p = re.search(r'Path\s+"([^"]+)"', b)
        f = re.search(r'Model\s+0\s+"([^"]+)"', b)
        sc = re.search(r'Scale\s+(-?[\d.]+)\s+(-?[\d.]+)\s+(-?[\d.]+)', b)
        of = re.search(r'Offset\s+(-?[\d.]+)\s+(-?[\d.]+)', b)
        zo = re.search(r'ZOffset\s+(-?[\d.]+)', b)
        fr = re.search(r'FrameIndex\s+\S+\s+\S+\s+0\s+(\d+)', b)
        if not (p and f and sc):
            continue
        out.setdefault(name, dict(
            path=p.group(1).rstrip('/'), model=f.group(1),
            scale=[float(x) for x in sc.groups()],
            off=[float(of.group(1)), float(of.group(2))] if of else [0.0, 0.0],
            zoff=float(zo.group(1)) if zo else 0.0,
            frame=int(fr.group(1)) if fr else 0))
    return out


def table_zs(rows):
    """RSQ_HandTable in the 1.96b layout, but keyed on the MODEL in hand.

    handfit_cards' own emitter writes `if (w is 'Class') return i`, which is right for
    a pack whose weapons it owns. Ours owns none of them, so Index reads the donor the
    model handler published -- exactly as RSR_Guns.Index does, and for the same reason:
    the gun is the model, not the weapon.
    """
    L = ["// generated by tools_kit/run_handfit.py from the shelf's cards -- do not edit by hand",
         '// Per gun: gun-hand frame (one hand, two hands), its hook and rotation, support frame,',
         "// its hook and rotation (ModifyBobLayer3D units), and where the support hand holds the",
         "// gun (metres in the gun hand's frame: forward, left, up). Ermac's poses, moved onto",
         "// each gun by the kit's ICP anchored on the card's palm / supportat.",
         '//',
         '// Keyed on the MODEL, not the weapon: the weapon belongs to whatever mod is loaded and',
         '// only its model is ours. Same lookup, same cvars, same reason as RSR_Guns.Index.',
         'class RSQ_HandTable abstract',
         '{',
         '\tclearscope static int Index(Weapon w)',
         '\t{',
         '\t\tif (!w) return 0;',
         '\t\treturn SlotForDonor(DonorInHand(HandOf(w)));',
         '\t}',
         '',
         '\tclearscope static int HandOf(Weapon w)',
         '\t{',
         '\t\treturn 0;',
         '\t}',
         '',
         '\t// The donor model worn by this hand, as RS_ForeignModelHandler published it. A cvar',
         "\t// because `struct CVar native` carries no scope qualifier and this is clearscope;",
         '\t// see the note on RSR_Guns.DonorInHand for why nothing else reaches across.',
         '\tclearscope static string DonorInHand(int hand)',
         '\t{',
         "\t\tlet cv = CVar.FindCVar(hand == 1 ? 'ms_donor_off' : 'ms_donor_main');",
         '\t\treturn cv ? cv.GetString() : "";',
         '\t}',
         '',
         '\tclearscope static int SlotForDonor(string donor)',
         '\t{',
         '\t\tif (donor.Length() == 0) return 0;']
    for i, r in enumerate(rows, 1):
        L.append('\t\tif (donor == "%s")\treturn %d;' % (r['cls'], i))
    L += ['\t\treturn 0;', '\t}', '']

    def strs(name, key):
        L.extend(['\tclearscope static String %s(int i)' % name, '\t{',
                  '\t\tstatic const String v[] = { "", %s };' % ', '.join('"%s"' % r[key] for r in rows),
                  '\t\treturn i > 0 && i < v.Size() ? v[i] : "";', '\t}', ''])

    def vecs(name, key):
        xs = ', '.join('%.3f' % r[key][0] for r in rows)
        ys = ', '.join('%.3f' % r[key][1] for r in rows)
        zs = ', '.join('%.3f' % r[key][2] for r in rows)
        L.extend(['\tclearscope static Vector3 %s(int i)' % name, '\t{',
                  '\t\tstatic const double x[] = { 0, %s };' % xs,
                  '\t\tstatic const double y[] = { 0, %s };' % ys,
                  '\t\tstatic const double z[] = { 0, %s };' % zs,
                  '\t\tif (i <= 0 || i >= x.Size())', '\t\t\treturn (0, 0, 0);',
                  '\t\treturn (x[i], y[i], z[i]);', '\t}', ''])

    strs('GunOne', 'one'); strs('GunTwo', 'two'); strs('Support', 'sup')
    vecs('GunHook', 'hook'); vecs('GunRot', 'rot')
    vecs('SupportHook', 'shook'); vecs('SupportRot', 'srot'); vecs('SupportPoint', 'spoint')
    strs('Trigger', 'trig')
    vecs('GunHookTwo', 'hook'); vecs('GunRotTwo', 'rot')
    L += ['}', '']
    return '\n'.join(L)


def main(out=OUT, sheets=True):
    c2q.modeldef_scales = rms.scales
    gp.MESH_ROOTS = rms.MESH_ROOTS
    cards = {w['cls']: w for w in c2q.load_cards(ROOT)}
    shelf = shelf_blocks()
    os.makedirs(SHEETS, exist_ok=True)

    rows, notes = [], {}
    for cls in sorted(shelf):
        w = cards.get(cls)
        if not w:
            notes[cls] = 'no card'; continue
        if 'palm' not in w['grip']:
            notes[cls] = 'card has no grip palm'; continue
        b = shelf[cls]
        mesh = gp.find_mesh(ROOT, b['path'], b['model'])
        if not os.path.exists(mesh):
            notes[cls] = 'mesh not found: %s' % mesh; continue
        it = dict(path=mesh, frame=b['frame'], scale=b['scale'],
                  off=[b['off'][0], b['off'][1], b['zoff']], color=[150, 155, 170])
        try:
            typ, _ = gp.gun_type(cls, w['keys'])
            two, one, sup, kind, trig = hf.POSE.get(typ, hf.POSE['rifle'])
            geo = c2q.geometry(w, tuple(b['scale']), (b['off'][0], b['off'][1], b['zoff']))
            palm = np.array(geo['palm'])
            gun_pts = hf.surface_points(it)
        except Exception as e:
            notes[cls] = 'unreadable: %s: %s' % (type(e).__name__, str(e)[:70]); continue

        key1 = 'hand:%d' % two
        if key1 not in hf.REGIONS:
            notes[cls] = 'no measured gripping face for Ermac pose %d' % two; continue
        t, err, why = hf.fit_gun(gun_pts, palm, key1)
        if t is None:
            notes[cls] = 'gun hand: ' + why; continue
        row = dict(cls=cls, one=hf.GUN_LETTER[one], two=hf.GUN_LETTER[two],
                   sup=hf.SUP_LETTER[sup], trig=trig,
                   hook=(round(t[1], 3), round(t[2], 3), round(-t[0], 3)),
                   rot=(0, 0, 0), srot=(0, 0, 0))
        info = ('%-12s gun hand %s F%+.1f L%+.1f U%+.1f, contact face %.2f cm off the gun'
                % (typ, key1, t[0], t[1], t[2], err))

        t2 = t.copy(); sp = palm / 100.0
        if kind == 'same':
            info += '; support cups the gun hand'
        else:
            sa = geo.get('supportat')
            skey = 'hand2:%d' % sup
            if not sa or skey not in hf.REGIONS:
                row.update(sup='', shook=(0, 0, 0), spoint=(0, 0, 0))
                notes[cls] = info + ('; no supportat on the card' if not sa
                                     else '; no measured face for support pose %d' % sup)
                rows.append(row); continue
            t2, err2, fp, why2 = hf.fit_support(gun_pts, hf.gun_tris(it), sa, skey)
            if t2 is None:
                row.update(sup='', shook=(0, 0, 0), spoint=(0, 0, 0))
                notes[cls] = info + '; support: ' + why2
                rows.append(row); continue
            sp = np.array(fp) / 100.0
            info += '; support %s at F %.1f, cylinder %.2f cm off the gun' % (skey, fp[0], err2)
        row.update(shook=(round(t2[1], 3), round(t2[2], 3), round(-t2[0], 3)),
                   spoint=tuple(np.round(sp, 3)))
        rows.append(row); notes[cls] = info

        if sheets:
            try:
                from PIL import Image
                import gunview
                items = [it, hf.hand_item('hand', two, t),
                         hf.hand_item('hand2', sup, t2, color=(120, 200, 140))]
                marks = [(*palm, 'palm', (255, 200, 60))]
                if geo.get('supportat'):
                    marks.append((*geo['supportat'], 'support', (120, 230, 140)))
                a = os.path.join(SHEETS, cls + '.side.png')
                bb = os.path.join(SHEETS, cls + '.bottom.png')
                gunview.view(items, a, 'side', px=5, marks=marks, title='%s hands' % cls)
                gunview.view(items, bb, 'bottom', px=5, marks=marks, title='%s hands' % cls)
                A, B = Image.open(a), Image.open(bb)
                O = Image.new('RGB', (max(A.width, B.width), A.height + B.height))
                O.paste(A, (0, 0)); O.paste(B, (0, A.height))
                O.save(os.path.join(SHEETS, cls + '.png'))
                os.remove(a); os.remove(bb)
            except Exception as e:
                notes[cls] += '; sheet failed: %s' % e

    open(out, 'w', encoding='utf-8').write(table_zs(rows))
    json.dump(dict(rows=rows, notes=notes), open(REPORT, 'w'), indent=1)

    for r in rows:
        print('  %-30s %s' % (r['cls'], notes[r['cls']]))
    skipped = {k: v for k, v in notes.items() if k not in {r['cls'] for r in rows}}
    print('\n%d shelf models have hands; %d do not:' % (len(rows), len(skipped)))
    from collections import Counter
    for why, n in Counter(re.sub(r'[-\d.]+', 'N', v) for v in skipped.values()).most_common():
        print('  %4d  %s' % (n, why))
    print('\n-> %s\n-> %s\n-> check sheets in %s' % (out, REPORT, SHEETS))
    return rows


if __name__ == '__main__':
    main(sys.argv[1] if len(sys.argv) > 1 else OUT)
